/**
 * Generates the database half of Miko's read guard from the data catalog:
 *
 *   1. a migration that creates the NOLOGIN role `miko_reader`, grants it SELECT on
 *      the readable columns of every readable table (never secrets, never excluded
 *      tables) and adds row-level-security policies so that, while a query runs as
 *      that role, it only sees rows of the project in `miko.project_id`;
 *   2. src/services/data-query/grants.generated.ts, the list of tables/columns the
 *      migration granted (the server only asks the role for those).
 *
 * Other roles are never affected: RLS is switched on only for tables where it was
 * off, together with a policy that lets every role except miko_reader through, so
 * the app (and anything else) sees exactly what it saw before. Every table is
 * handled in its own block that cannot fail the migration.
 *
 * Run after adding tables/columns you want Miko to read:
 *   npx tsx scripts/generate-miko-guard.ts            (name defaults to <timestamp>_miko_reader_guard)
 */
import fs from 'fs';
import path from 'path';
import { buildCatalog, type CatalogModel } from '../src/services/data-query/catalog';

const ROLE = 'miko_reader';
const SETTING = `NULLIF(current_setting('miko.project_id', true), '')::uuid`;
const q = (id: string) => `"${id.replace(/"/g, '""')}"`;

const catalog = buildCatalog();

function rowRule(entry: CatalogModel): string {
  if (entry.scope === 'project') return `${q('projectId')} = ${SETTING}`;
  if (entry.scope === 'global' || entry.scope === 'user') return 'true';
  // child: EXISTS through each hop up to the project table.
  const tables: string[] = [];
  const conds: string[] = [];
  let outer = q(entry.table);
  entry.path.forEach((step, i) => {
    const alias = `p${i + 1}`;
    tables.push(`${q(catalog.get(step.target)!.table)} ${alias}`);
    conds.push(`${alias}.${q('id')} = ${outer}.${q(step.fk)}`);
    outer = alias;
  });
  conds.push(`${outer}.${q('projectId')} = ${SETTING}`);
  return `EXISTS (SELECT 1 FROM ${tables.join(', ')} WHERE ${conds.join(' AND ')})`;
}

/** Readable columns, plus what the row policies themselves read (projectId, path keys). */
function grantColumns(entry: CatalogModel): string[] {
  const cols = new Set(entry.fields.keys());
  cols.add('id');
  if (entry.scope === 'project') cols.add('projectId');
  if (entry.path[0]) cols.add(entry.path[0].fk);
  // A table that is a hop on some child's path must expose its own projectId / next key to that policy.
  for (const other of catalog.values()) {
    other.path.forEach((step, i) => {
      if (step.target !== entry.model) return;
      const next = other.path[i + 1];
      if (next) cols.add(next.fk);
      else cols.add('projectId');
    });
  }
  return [...cols];
}

const blocks: string[] = [];
const grants: Record<string, string[]> = {};
for (const entry of [...catalog.values()].sort((a, b) => a.table.localeCompare(b.table))) {
  const cols = grantColumns(entry);
  grants[entry.model] = [...entry.fields.keys()];
  const t = q(entry.table);
  blocks.push(`-- ${entry.model} (${entry.scope})
DO $$
DECLARE rls_on boolean;
BEGIN
  SELECT c.relrowsecurity INTO rls_on FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relname = '${entry.table}';
  IF rls_on IS NULL OR NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${ROLE}') THEN RETURN; END IF;
  GRANT SELECT (${cols.map(q).join(', ')}) ON ${t} TO ${ROLE};
  IF NOT rls_on THEN
    ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;
    DROP POLICY IF EXISTS miko_everyone_else ON ${t};
    CREATE POLICY miko_everyone_else ON ${t} FOR ALL TO PUBLIC
      USING (current_user <> '${ROLE}') WITH CHECK (current_user <> '${ROLE}');
  END IF;
  DROP POLICY IF EXISTS miko_reader_rows ON ${t};
  CREATE POLICY miko_reader_rows ON ${t} FOR SELECT TO ${ROLE} USING (${rowRule(entry)});
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'miko guard skipped ${entry.table}: %', SQLERRM;
END $$;`);
}

const header = `-- Miko read guard (generated by scripts/generate-miko-guard.ts; do not edit by hand).
-- A NOLOGIN role that can only SELECT readable columns of readable tables, and only rows of
-- the project set in miko.project_id. The app's own role is unaffected (see the script header).
-- Every statement is wrapped so this migration can never fail a deploy.

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${ROLE}') THEN
    CREATE ROLE ${ROLE} NOLOGIN NOINHERIT;
  END IF;
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'miko guard: could not create role: %', SQLERRM;
END $$;

DO $$
BEGIN
  EXECUTE format('GRANT ${ROLE} TO %I', current_user);
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'miko guard: could not grant role: %', SQLERRM;
END $$;

DO $$
BEGIN
  GRANT USAGE ON SCHEMA public TO ${ROLE};
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'miko guard: could not grant schema usage: %', SQLERRM;
END $$;
`;

const root = path.resolve(__dirname, '..');
const name =
  process.argv[2] ??
  `${new Date().toISOString().replace(/[-:T]/g, '').slice(0, 14)}_miko_reader_guard`;
const dir = path.join(root, 'prisma', 'migrations', name);
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'migration.sql'), `${header}\n${blocks.join('\n\n')}\n`);

const ts = `// Generated by scripts/generate-miko-guard.ts together with migration ${name}. Do not edit by hand.
// Tables and columns the miko_reader role was granted; the data query asks the role for nothing else.
export const GUARD_MIGRATION = '${name}';
export const GUARDED_COLUMNS: Record<string, readonly string[]> = ${JSON.stringify(grants, null, 2)};
`;
fs.writeFileSync(path.join(root, 'src', 'services', 'data-query', 'grants.generated.ts'), ts);
console.log(`Wrote ${dir}/migration.sql (${blocks.length} tables) and grants.generated.ts`);
